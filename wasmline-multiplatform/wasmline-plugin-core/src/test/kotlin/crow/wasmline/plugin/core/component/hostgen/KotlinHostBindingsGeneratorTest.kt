    @Test
    fun generatesAndCompilesMultipleResourcesWithNestedOwnedResults() = withGeneratorDirectory { root ->
        val result = KotlinHostBindingsGenerator.generate(
            KotlinHostBindingsRequest(
                File(sampleRoot(), "kv"),
                File(root, "generated"),
                "kv-plugin",
                "generated.kv",
                allowResources = true,
            ),
        )
        val source = result.outputFile.readText()
        assertTrue(source.contains("class Bucket internal constructor("))
        assertTrue(source.contains("class WatchHandle internal constructor("))
        assertTrue(source.contains("WasmlineWitResult<Bucket, KvError>"))
        assertTrue(source.contains("WasmlineWitResult<WatchHandle, KvError>"))
        assertTrue(source.contains("Pair<List<Entry>, String?>"))
        assertTrue(source.contains("interface HostClock"))

        val output = File(root, "classes")
        val runtimeJar = File(WasmlineComponentContract::class.java.protectionDomain.codeSource.location.toURI())
        val stdlibJar = File(Unit::class.java.protectionDomain.codeSource.location.toURI())
        val compile = K2JVMCompiler().exec(
            System.err,
            "-no-reflect",
            "-classpath",
            listOf(runtimeJar, stdlibJar).joinToString(File.pathSeparator, transform = File::getAbsolutePath),
            "-d",
            output.absolutePath,
            result.outputFile.absolutePath,
        )

        assertEquals(ExitCode.OK, compile)
        assertTrue(File(output, "generated/kv/KvPluginWorld\$Bucket.class").isFile)
        assertTrue(File(output, "generated/kv/KvPluginWorld\$WatchHandle.class").isFile)
    }

    private fun sampleRoot(): File {
        val resourceRoot = checkNotNull(javaClass.classLoader.getResource("fixtures/component-model-wit-samples")) {
            "Unable to locate component model WIT samples test fixture."
        }
        return File(resourceRoot.toURI())
    }
}

private inline fun withGeneratorDirectory(block: (File) -> Unit) {
    val directory = createTempDirectory("wasmline-host-wit-generator-test").toFile()
    try {
        block(directory)
    } finally {
        directory.deleteRecursively()
    }
}
